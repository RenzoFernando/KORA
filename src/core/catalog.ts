export const normalize = (text: string) =>
  text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
export function filterCatalog(catalog: Release[], city: string, genre: string, query: string) {
  return catalog.filter(
    (r) =>
      r.status === 'active' &&
      (city === 'Colombia' || r.city === city) &&
      (genre === 'Todos' || r.genre === genre) &&
      normalize(r.artist + ' ' + r.title + ' ' + r.genre + ' ' + r.city).includes(
        normalize(query.trim()),
      ),
  );
}
export function safeUrl(value: string): string {
  try {
    const url = new URL(value);
    return url.protocol === 'https:' && !url.username && !url.password ? url.href : '';
  } catch {
    return '';
  }
}
export function embedUrl(release: Release, dark = false) {
  if (
    release.playback !== 'bandcamp' ||
    !/^\d+$/.test(release.embedId || '') ||
    !['track', 'album'].includes(release.embedType || '')
  )
    return '';
  return (
    'https://bandcamp.com/EmbeddedPlayer/' +
    release.embedType +
    '=' +
    release.embedId +
    '/size=large/bgcol=' +
    (dark ? '17171b' : 'ffffff') +
    '/linkcol=f1871c/artwork=none/tracklist=false/transparent=true/'
  );
}
